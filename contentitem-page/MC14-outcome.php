<h2>Introduction:</h2>
<p>
WTO’s 14th Ministerial Conference was held in Yaoundé, Cameroon, between 26 - 30th March 2026. On the agenda was the so-called WTO reform which was presented as the new WTO for the future. 
The ministerial ended in the middle of the night or morning the 30th with no outcome. The ministers decided to move the negotiations to Geneva. This no-outcome led to two moratoriums expiring (since no agreement to extend them); one was the prohibition on duties on electronic transmissions, and the other was that no country can sue others over TRIPS non-violation complaints. Both moratoriums expiring have huge consequences, which you can read about in the below articles from the OWINFS Network. 
<p>
