Dear Dr Ngozi,
<p>
Re: Civil Society Participation in and Contribution to WTO Public Forums
<p>
We are writing as Civil Society Organisations (CSOs) from a range of countries, working with farmers, fishers and small producers who are responsible for the vast majority of the world’s businesses and jobs, and most of the world’s food, as well as workers and citizens. Our collective goal is to ensure that the work of the WTO brings benefits to the communities we work with or at least has no negative effects on them.
<p>
When Ministers adopted the Marrakesh Agreement they included a specific reference to Non-Governmental Organizations (NGOs) in Article V:2. On 18 July 1996 the General Council further clarified the framework for relations with NGOs by adopting a set of guidelines (<a href="https://www.wto.org/english/forums_e/ngo_e/guide_e.htm">WT/L/162</a>) which recognise the valuable role of NGOs in contributing to “the accuracy and richness of the public debate” and agree to “improve transparency and develop communication with NGOs". The interaction with NGOs was to be developed through such means as an “ad hoc basis of symposia on specific WTO-related issues”. This is in addition to the national level engagement that CSOs engage in. It is highly doubtful that this year's Public Forum with so few sessions organised by NGOs, is fulfilling this requirement of interaction with NGOs. 
<p>
As we have raised with you on a number of previous occasions, serious and excessive barriers have been put in the way of civil society participation at WTO events, for example ministerial meetings in Abu Dhabi and Buenos Aires. It is also the case that the space for CSO participation at the Public Forum has shrunk significantly. CSOs not only participate, but contribute immensely to the process and content of trade policymaking through the WTO and by engaging in its key events such as the Ministerials and the Public Forum.
<p>
The public forum was established in response to significant concerns that the WTO was too opaque and offered too few opportunities for stakeholder engagement. The WTO describes the forum as the WTO’s “largest outreach event,” and we have consistently engaged with the forum as session organisers and participants. Yet there has been an increasing trend to exclude CSOs as session organisers. Our analysis of the released programme suggests that just 5% of total sessions this year will be hosted by CSOs. We understand that the WTO secretariat has suggested that 30% of the slots is going to NGOs, a discrepancy we believe can only be possible if a number of stakeholders is being mis-categorised.  Business, government and the WTO itself are given much larger shares of the sessions.
<p>
This approach means that the WTO is not taking into account the diversity of voices, which will ultimately lead to weaker decision making and increase the likelihood that initiatives will fail. It will lead to the further erosion of the credibility of the organisation, in turn making it extremely difficult to achieve many of the changes that are needed if the WTO is to be effective: if the public do not see the WTO as legitimate, Member States have much less incentive to engage constructively.
<p>
Acknowledging that plans are already underway for this year’s Public Forum, we are keen to work with you to ensure that the 2027 forum is more inclusive of civil society voices.
<p>
In the first instance, we would be grateful if you could provide answers to the following questions:
<ol>
<li>What is the WTO’s current definition of a civil society organisation (that allows it to argue CSOs represent 30% of session organisers)? How was this agreed and was any consultation undertaken with member states, stakeholders and specifically CSOs?

<li>What, if any, session allocation does the WTO make to different categories of stakeholders? If no allocation is made, please explain the reason for this.

<li>What are the criteria for accepting or rejecting proposed panels? In particular, reference is often made to the ‘quality and relevance’ of sessions, please provide further explanation of this.
</ol>
<p>
We also have the following recommendations that we believe will demonstrate your commitment to ensuring the WTO is an inclusive organisation, committed to taking account of a diversity of voices:
<ol>
<li>
The WTO’s definition of CSO needs urgent review. Our strong recommendation is that to qualify as a CSO, an organisation must be able to demonstrate direct accountability to workers, farmers, fishers, producers or the general public.
<li>
The WTO must establish a fair allocation of time to different categories of stakeholder, in consultation with those stakeholders. 
<li>
The WTO's primary role should be to facilitate the participation of others, rather than taking a significant share of the slots itself. This is in line with the spirit of the forum, which is to allow stakeholders the space to share their views and contribute to the process of trade policymaking in the WTO. A deadline could be given for allocated slots to be taken up before they are offered to other stakeholders.
<li>
The WTO must clearly and openly publish its criteria for accepting or rejecting sessions. It should ensure that one of the criteria to be considered is that the session includes the participation of communities that will be impacted by WTO rules.
<li>
Urgently reinstate interpretation services in order to ensure it reaches as wide an audience as possible, contributing to better policy making. 
</ol>
<p>
We would like to propose a meeting between you and some of our representatives at the time of the public forum so that we can contribute to the process of building a credible, transparent, participatory and truly diverse “Public” Forum. 
<p>
Yours sincerely,
