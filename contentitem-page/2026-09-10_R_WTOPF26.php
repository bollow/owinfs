<p>
<b>GENEVA</b> — A global network representing farmers, fishers, workers, and small producers
has issued an open <a href="2026-09-10_L_WTOPF26">letter</a>
to World Trade Organization (WTO) Director-General Dr. Ngozi
Okonjo-Iweala, warning that civil society is being systematically sidelined from the
organization’s primary outreach event.
<p>
The civil society organisations, coordinated by the global network Our World Is Not For Sale
(OWINFS), reports that Civil Society Organizations (CSOs) will organize just 5% of the total
sessions at this year’s WTO Public Forum, disputing Secretariat claims that CSOs represent
30% of session hosts due to miscategorized corporate and institutional entries. This
dramatic drop in representation follows severe, ongoing barriers faced by CSOs at recent
WTO Ministerial Conferences in Buenos Aires and Abu Dhabi.
<blockquote>
“The Public Forum was initially launched in 2001 as a way to seek some license for
the WTO following the disastrous Seattle ministerial in 1999 and widespread
protests against corporate globalisation. Since then it has steadily deteriorated to
become a propaganda tool for the WTO Secretariat and silenced civil society voices
to allow international organisations, Member States and business to dominate”, <b>says
Prof Em. Jane Kelsey, University of Auckland</b>.
</blockquote>
<p>
To restore accountability and rebuild stakeholder trust ahead of the 2027 Public Forum, the
civil society organisations are urging the WTO Secretariat to take key steps:
<ul>
<li><b>Redefine CSO Criteria:</b> Restrict the CSO classification to entities with direct
accountability to workers, farmers, fishers, small producers, and the general public
<li><b>Establish Fair Stakeholder Allocations:</b> Create clear, consultative slot allocations for
different stakeholder groups.
<li><b>Refocus WTO’s Role:</b> Limit WTO-hosted panels to prioritize external stakeholder
participation
<li><b>Transparent Selection Criteria:</b> Publish clear selection guidelines that explicitly value
the inclusion of communities directly impacted by trade policies
<li><b>Reinstate Interpretation Services:</b> Restore multilingual interpretation to ensure
broad, accessible, and inclusive global participation
</ul>
<p>
The global civil society network has requested an urgent meeting with Director-General
Okonjo-Iweala during the upcoming Public Forum to address these concerns and establish a
framework for inclusive participation moving forward.
<p>
<b>QUOTES FROM CIVIL SOCIETY ORGANISATIONS:</b>
<blockquote>
“WTO’s failure to accommodate Public Forum sessions proposed by legitimate non-
profit organizations is very disappointing, in particular because it deprives WTO
members of accurate and rich public debate, and fails to improve transparency and
develop communication with NGOs, who are a valuable resource, thus contradicting
the 18 July 1996 General Council Guidelines for arrangements on relations with Non-
Governmental Organizations (WT/L/162). Indeed, failure to encourage participation
by NGOs results in insufficient attention to issues other than the trade law issues on
which most WTO participants are expert.” <b>Richard Hill, Association for Proper
Internet Governance, Geneva, Switzerland.</b>
<p>
“The shrinking space for civil society at the WTO is not an administrative issue—it is
a democratic and legitimacy crisis. An institution that claims to promote
transparency cannot marginalise the voices of farmers, fishers, workers, small
producers and affected communities while giving disproportionate space to
governments, business and itself. Trade rules have real consequences for people’s
rights and livelihoods. Those most affected must have the power to shape the
debate, not merely be invited as spectators. Without meaningful and equal civil
society participation, the WTO’s ‘Public Forum’ risks becoming nothing more than a
public-relations exercise. A public forum without the public is not a public forum.”
<b>Rahmat Maulana Sidik, Executive Director, Indonesia for Global Justice (IGJ)</b>
<p>
“Africa must have a meaningful seat at the table where international trade rules are
shaped. It is concerning that legitimate African and Global South organisations
representing farmers, workers, women, youth, small producers and affected
communities have been excluded from organising sessions at this year’s WTO Public
Forum. These voices bring perspectives that are often missing from formal trade-
related discussions. Their exclusion limits meaningful participation and undermines
the diversity of perspectives needed to shape trade policies that directly affect our
economies and livelihoods. The WTO must ensure that its engagement platforms,
including the Public Forum, are genuinely inclusive and provide greater space for
Global South organisations to participate, contribute and advance Global South
voices in shaping the international trading system.” <b>Ms. Jane Nalunga, Executive
Director, Southern and Eastern Africa Trade Information and Negotiations Institute
(SEATINI)</b>
<p>
“I am deeply worried about the undemocratic developments at the WTO. We need
now more than ever to hear the voices of civil society organizations, especially now
that authoritarian powers are on the rise and developing countries/Global South
countries are under more pressure than ever.” <b>Eline Melby Lorentsen, deputy chair
person, the Norwegian Trade Campaign</b>
<p>
“It is genuinely troubling that this year's Forum offers so little space for opposing
voices — without that contrast, there can be no real debate about where the
multilateral trading system is heading. Budget constraints and shorter schedules are
real limitations, but when choices have to be made, they should protect space for
civil society. That was the Public Forum's reason for being in the first place.” <b>Sofía
Scasserra, Associated Researcher, GFNE / TNI</b>
<p>
“The WTO launched the Public Forum to appear responsive to protests of corporate
globalization — but now there is no longer even a pretense of the WTO’s supposedly
“public” forum facilitating debate across a variety of perspectives. It’s a perfect
reflection of the opacity of the WTO itself, where rich countries dominate in private
“green room” negotiations, sidelining developing countries and excluding the public
entirely.” <b>Melanie Foley, Global Trade Watch Deputy Director, Public Citizen</b>
</blockquote>
