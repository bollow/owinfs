<b>ABOUT OWINFS</b>
The “Our World Is Not For Sale” (OWINFS) network is a loose grouping of organizations and
social movements of public interest groups, development advocates, farmer and fisherfolk
networks, environmental organisations, trade unions, and other civil society, from the global
north and south, worldwide fighting the current model of corporate globalization embodied
in the global trading system. OWINFS is committed to a sustainable, socially just, democratic
and accountable multilateral trading system. The network includes over 200 organisations
worldwide. <a href="https://owinfs.org/">https://owinfs.org/</a>
